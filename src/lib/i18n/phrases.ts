const CATALOG: Record<LangCode, Record<string, string>> = {
  en: {},
  fr: FR,
  ne: NE,
};

/** Translate a literal English UI string; returns source text if missing. */
export function translatePhrase(lang: LangCode, text: string): string {
  if (lang === "en" || !text) return text;
  return CATALOG[lang][text] ?? text;
}

/** Translate with simple `{name}` style interpolation. */
export function translatePhraseFormat(
  lang: LangCode,
  text: string,
  vars?: Record<string, string | number>,
): string {
  let out = translatePhrase(lang, text);
  if (!vars) return out;
  for (const [k, v] of Object.entries(vars)) {
    out = out.split(`{${k}}`).join(String(v));
  }
  return out;
}
